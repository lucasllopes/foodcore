package com.fiap.foodcore.infrastructure.presenter;

import com.fiap.foodcore.application.usecase.input.CreateItemInput;
import com.fiap.foodcore.application.usecase.input.UpdateItemInput;
import com.fiap.foodcore.application.usecase.output.ItemCreateOutput;
import com.fiap.foodcore.infrastructure.web.controller.dto.ItemCreateRequestDTO;
import com.fiap.foodcore.infrastructure.web.controller.dto.ItemCreateResponseDTO;
import com.fiap.foodcore.infrastructure.web.controller.dto.ItemUpdateRequestDTO;

import java.util.List;

public class ItemPresenter {

    public static List<ItemCreateResponseDTO> toDtoList(List<ItemCreateOutput> outputs) {
        return outputs.stream()
                .map(output -> new ItemCreateResponseDTO(
                        output.id(),
                        output.name(),
                        output.description(),
                        output.price(),
                        output.availability(),
                        output.photo()
                ))
                .toList();
    }

    public static ItemCreateOutput toOutput(ItemCreateRequestDTO dto) {
        return new ItemCreateOutput(
                null, // ID will be generated by the system
                dto.name(),
                dto.description(),
                dto.price(),
                dto.availability(),
                dto.photo()
        );
    }

    public static ItemCreateResponseDTO toDto(ItemCreateOutput output) {
        return new ItemCreateResponseDTO(
                output.id(),
                output.name(),
                output.description(),
                output.price(),
                output.availability(),
                output.photo()
        );
    }

    public static CreateItemInput toInput(ItemCreateRequestDTO dto) {
        return new CreateItemInput(
                dto.name(),
                dto.description(),
                dto.price(),
                dto.availability(),
                dto.photo()
        );
    }

    public static UpdateItemInput toUpdateInput(ItemUpdateRequestDTO dto) {
        return new UpdateItemInput(
                dto.id(),
                dto.name(),
                dto.description(),
                dto.price(),
                dto.availability(),
                dto.photo()
        );
    }

}
